import { getRouterParam, readBody } from '@nuxt/nitro-server/h3'
import { getApplication } from '../../../bootstrap/application'
import { apiHandler, success } from '../../../platform/http/response'
import { currentUser } from '../../../platform/http/session'
import { idSchema } from '../../../../shared/validation/workspace'
import { notificationPreferencesSchema } from '../../../../shared/validation/workspaceSettings'

export default apiHandler(async (event) => {
  const id = idSchema.parse(getRouterParam(event, 'workspaceId'))
  const userId = currentUser(event).id
  return success(await getApplication().services.settings.notifications(id, userId, notificationPreferencesSchema.parse(await readBody(event))))
})
